/** The 34 provinces keep their Vietnamese names (they are what the courier reads); cities read "… City" in English. */
export function provinceLabel(province: string, lang: Lang): string {
	if (lang === "vi") return province;
	return province.startsWith("Thành phố ") ? `${province.slice("Thành phố ".length)} City` : province;
}

